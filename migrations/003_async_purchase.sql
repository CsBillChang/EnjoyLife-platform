CREATE TABLE IF NOT EXISTS purchase_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    activity_id BIGINT UNSIGNED NOT NULL,
    scope VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PURCHASE',
    idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    params_digest BINARY(32) NOT NULL,
    accepted_at DATETIME(6) NOT NULL,
    processing_deadline DATETIME(6) NOT NULL,
    shop_id BIGINT UNSIGNED NOT NULL,
    price_cents BIGINT UNSIGNED NOT NULL,
    currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    generation BIGINT UNSIGNED NOT NULL,
    status ENUM('RECEIVED', 'ADMITTED', 'SUCCEEDED', 'FAILED') NOT NULL,
    order_id BIGINT UNSIGNED NULL,
    error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_purchase_requests_request_id (request_id),
    UNIQUE KEY uk_purchase_requests_user_scope_key (user_id, scope, idempotency_key),
    KEY idx_purchase_requests_status_deadline (status, processing_deadline),
    KEY idx_purchase_requests_user_activity (user_id, activity_id, status),
    CONSTRAINT fk_purchase_requests_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_purchase_requests_activity FOREIGN KEY (activity_id) REFERENCES coupon_activities(id),
    CONSTRAINT fk_purchase_requests_shop FOREIGN KEY (shop_id) REFERENCES shops(id),
    CONSTRAINT fk_purchase_requests_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT chk_purchase_request_deadline CHECK (accepted_at < processing_deadline)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS outbox_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    aggregate_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    aggregate_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload JSON NOT NULL,
    status ENUM('PENDING', 'SENT') NOT NULL DEFAULT 'PENDING',
    attempts INT UNSIGNED NOT NULL DEFAULT 0,
    available_at DATETIME(6) NOT NULL,
    lease_until DATETIME(6) NULL,
    sent_at DATETIME(6) NULL,
    last_error VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_outbox_events_event_id (event_id),
    KEY idx_outbox_dispatch (status, available_at, lease_until, id),
    CONSTRAINT chk_outbox_attempts CHECK (attempts <= 1000)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS recovery_tasks (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    kind VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
    status ENUM('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED') NOT NULL DEFAULT 'PENDING',
    attempts INT UNSIGNED NOT NULL DEFAULT 0,
    available_at DATETIME(6) NOT NULL,
    lease_until DATETIME(6) NULL,
    payload JSON NOT NULL,
    last_error VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_recovery_tasks_kind_source (kind, source_id),
    KEY idx_recovery_tasks_dispatch (status, available_at, lease_until, id)
) ENGINE=InnoDB;
